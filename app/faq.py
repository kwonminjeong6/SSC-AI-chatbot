def match(query: str) -> Optional[dict]:
    """질문에 맞는 검증 답변이 있으면 {'answer','sources'}를, 없으면 None을 돌려줍니다."""
    text = _compact(query)
    for item in FAQ:
        if any(_compact(word) in text for word in item["exclude"]):
            continue
        if all(any(_compact(word) in text for word in group) for group in item["require"]):
            logger.info("FAQ 적중: %s", item["id"])
            answer: Callable[[str], str] | str = item.get("answer_fn") or item["answer"]
            return {"answer": answer(query) if callable(answer) else answer, "sources": list(item["sources"])}
    return None